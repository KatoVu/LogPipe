"""``logpipe deploy render``: one topology file -> what each host runs.

A topology names a domain and its tenants. Each tenant is served at ``<tenant>.<domain>`` by
its own server container on the hosted VPS (behind the Traefik from ``deploy/ansible``), and
says where its rows live:

- ``residency: hosted``: a ClickHouse for the tenant on the VPS too.
- ``residency: client``: the rows stay on the client's network. The VPS runs
  ``server --store remote``; the client runs ``logpipe dataplane`` beside their own
  ClickHouse, dialing out to ``wss://<tenant>.<domain>/dataplane``.

``components`` lists the parts of the flow a tenant runs. ``parse``, ``store`` and ``detect``
are the pipeline itself; ``enrich`` (the LLM: masks, key names, Ask) and ``graph`` (the
component graph) can be left out.

Output, in ``--out``: ``hosted/`` (compose + .env for the VPS) and ``client-<tenant>/`` for each
client-residency tenant (compose + .env + README to hand over). Generated secrets are kept in
``secrets.env`` there and reused on the next render, so re-rendering never rotates a key.
"""

from __future__ import annotations

import re
import secrets
import shutil
from pathlib import Path

import yaml

COMPONENTS = ("parse", "store", "detect", "enrich", "graph")
REQUIRED = {"parse", "store", "detect"}
NAME = re.compile(r"^[a-z][a-z0-9-]{0,30}$")
CLICKHOUSE_IMAGE = "clickhouse/clickhouse-server:25.8"
LLM_KEYS = (
    "ANTHROPIC_API_KEY",
    "OPENAI_API_KEY",
    "GOOGLE_API_KEY",
    "GEMINI_API_KEY",
    "GROQ_API_KEY",
)
INIT_SCRIPT = Path(__file__).resolve().parent.parent / "docker" / "clickhouse-init.sh"


def load(path: Path) -> dict:
    """The topology, checked and with defaults filled in; a ValueError names what is wrong."""
    topo = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(topo, dict) or not isinstance(topo.get("domain"), str):
        raise ValueError("a topology needs `domain:` (tenants are served at <tenant>.<domain>)")  # noqa: TRY004 - shown to the person as a config error
    tenants = topo.get("tenants")
    if not isinstance(tenants, dict) or not tenants:
        raise ValueError("a topology needs at least one tenant under `tenants:`")
    out = {
        "domain": topo["domain"],
        "images": str(topo.get("images", "ghcr.io/katovu")),
        "tag": str(topo.get("tag", "latest")),
        "tenants": {},
    }
    for name, spec in tenants.items():
        spec = spec or {}
        if not isinstance(name, str) or not NAME.match(name):
            raise ValueError(f"tenant {name!r}: lowercase letters, digits and '-', up to 31")
        residency = spec.get("residency", "hosted")
        if residency not in ("hosted", "client"):
            raise ValueError(f"tenant {name}: residency is `hosted` or `client`")
        # shortcut: ClickHouse only; MongoDB tenants need its init script and users here first.
        if spec.get("store", "clickhouse") != "clickhouse":
            raise ValueError(f"tenant {name}: deploy render supports `store: clickhouse` only")
        components = list(spec.get("components", COMPONENTS))
        if unknown := set(components) - set(COMPONENTS):
            raise ValueError(f"tenant {name}: unknown components {sorted(unknown)}")
        if missing := REQUIRED - set(components):
            raise ValueError(f"tenant {name}: {sorted(missing)} cannot be left out")
        llm = str(spec.get("llm", "offline"))
        if "enrich" in components and llm == "offline":
            raise ValueError(f"tenant {name}: `enrich` needs an `llm:` (e.g. llm:anthropic)")
        out["tenants"][name] = {
            "residency": residency,
            "components": components,
            "llm": llm if "enrich" in components else "offline",
        }
    return out


def _secrets(path: Path, names: list[str]) -> dict[str, str]:
    known: dict[str, str] = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.startswith("#"):
                k, v = line.split("=", 1)
                known[k] = v
    for n in names:
        known.setdefault(n, secrets.token_urlsafe(24))
    path.write_text(
        "# generated by `logpipe deploy render`; reused on every render. Keep it secret.\n"
        + "".join(f"{k}={v}\n" for k, v in sorted(known.items())),
        encoding="utf-8",
    )
    path.chmod(0o600)
    return known


def _var(tenant: str, what: str) -> str:
    return f"{tenant.upper().replace('-', '_')}_{what}"


def _clickhouse(tenant: str) -> dict:
    return {
        "image": CLICKHOUSE_IMAGE,
        "restart": "unless-stopped",
        "environment": {
            "CLICKHOUSE_USER": "logpipe",
            "CLICKHOUSE_PASSWORD": f"${{{_var(tenant, 'CH_PASSWORD')}}}",
            "CLICKHOUSE_DB": "logpipe",
            "CLICKHOUSE_DEFAULT_ACCESS_MANAGEMENT": "1",
            "CLICKHOUSE_READONLY_USER": "logpipe_ro",
            "CLICKHOUSE_READONLY_PASSWORD": f"${{{_var(tenant, 'CH_RO_PASSWORD')}}}",
        },
        "volumes": [
            f"{tenant}-clickhouse:/var/lib/clickhouse",
            "./clickhouse-init.sh:/docker-entrypoint-initdb.d/clickhouse-init.sh:ro",
        ],
        "ulimits": {"nofile": {"soft": 262144, "hard": 262144}},
        "healthcheck": {
            "test": [
                "CMD-SHELL",
                (
                    "clickhouse-client --user $${CLICKHOUSE_USER} "
                    "--password $${CLICKHOUSE_PASSWORD} -q 'SELECT 1'"
                ),
            ],
            "interval": "10s",
            "retries": 10,
        },
    }


def _clickhouse_env(tenant: str, host: str) -> dict:
    return {
        "CLICKHOUSE_HOST": host,
        "CLICKHOUSE_PORT": "8123",
        "CLICKHOUSE_USER": "logpipe",
        "CLICKHOUSE_PASSWORD": f"${{{_var(tenant, 'CH_PASSWORD')}}}",
        "CLICKHOUSE_DB": "logpipe",
        "CLICKHOUSE_READONLY_USER": "logpipe_ro",
        "CLICKHOUSE_READONLY_PASSWORD": f"${{{_var(tenant, 'CH_RO_PASSWORD')}}}",
    }


def _server(topo: dict, tenant: str, spec: dict) -> dict:
    remote = spec["residency"] == "client"
    host = f"{tenant}.{topo['domain']}"
    router = f"logpipe-{tenant}"
    env = {
        "LLM_BACKEND": spec["llm"],
        "LOGPIPE_GRAPH_ENABLED": str("graph" in spec["components"]).lower(),
        "LOGPIPE_ADMIN_PASSWORD": f"${{{_var(tenant, 'ADMIN_PASSWORD')}}}",
        "LOGPIPE_LOG_FORMAT": "json",
        **{k: f"${{{k}:-}}" for k in LLM_KEYS},
    }
    if remote:
        env["LOGPIPE_DATAPLANE_KEY"] = f"${{{_var(tenant, 'DATAPLANE_KEY')}}}"
    else:
        env |= _clickhouse_env(tenant, f"{tenant}-clickhouse")
    labels = {
        "traefik.enable": "true",
        f"traefik.http.routers.{router}.rule": f"Host(`{host}`)",
        f"traefik.http.routers.{router}.entrypoints": "websecure",
        f"traefik.http.routers.{router}.service": router,
        f"traefik.http.services.{router}.loadbalancer.server.port": "8080",
    }
    if remote:
        labels |= {
            f"traefik.http.routers.{router}-dataplane.rule": (
                f"Host(`{host}`) && PathPrefix(`/dataplane`)"
            ),
            f"traefik.http.routers.{router}-dataplane.entrypoints": "websecure",
            f"traefik.http.routers.{router}-dataplane.service": f"{router}-dataplane",
            f"traefik.http.services.{router}-dataplane.loadbalancer.server.port": "8090",
        }
    service = {
        "image": f"{topo['images']}/logpipe-server:{topo['tag']}",
        "restart": "unless-stopped",
        "command": ["logpipe", "server", "--host", "0.0.0.0", "--port", "8080"]
        + ["--store", "remote" if remote else "clickhouse", "--queue", "memory"],
        "environment": env,
        "volumes": [f"{tenant}-data:/app/artifacts"],
        "networks": ["edge"] if remote else ["edge", tenant],
        "labels": labels,
        "logging": {"driver": "json-file", "options": {"max-size": "10m", "max-file": "5"}},
    }
    if not remote:
        service["depends_on"] = {f"{tenant}-clickhouse": {"condition": "service_healthy"}}
    return service


def _write(path: Path, compose: dict, env: dict[str, str]) -> None:
    path.mkdir(parents=True, exist_ok=True)
    (path / "docker-compose.yml").write_text(
        "# generated by `logpipe deploy render`: edit the topology and render again\n"
        + yaml.safe_dump(compose, sort_keys=False),
        encoding="utf-8",
    )
    (path / ".env").write_text("".join(f"{k}={v}\n" for k, v in env.items()), encoding="utf-8")
    (path / ".env").chmod(0o600)


CLIENT_README = """# logpipe dataplane for {tenant}

Your logs stay on this machine: the dataplane keeps the parsed rows, the review samples and
the server's settings in the ClickHouse below. It only connects out, to
`wss://{host}/dataplane`; nothing here needs an inbound port.

    docker compose up -d
    docker compose logs -f dataplane     # "[dataplane] connected to ..."

Point your agents at `https://{host}` (the UI is there too). If the dataplane is down, the
server refuses new logs and the agents keep them on disk until it is back.

`.env` holds this site's key and database passwords: keep it here, it is not needed anywhere else.
"""


def render(topo: dict, out: Path) -> list[Path]:
    """Write every host's files under ``out``; returns the directories written."""
    out.mkdir(parents=True, exist_ok=True)
    tenants = topo["tenants"]
    names = []
    for t, spec in tenants.items():
        names += [_var(t, "ADMIN_PASSWORD"), _var(t, "CH_PASSWORD"), _var(t, "CH_RO_PASSWORD")]
        if spec["residency"] == "client":
            names.append(_var(t, "DATAPLANE_KEY"))
    known = _secrets(out / "secrets.env", names)

    hosted_services: dict = {}
    volumes: dict = {}
    networks: dict = {"edge": {"name": "${TRAEFIK_NETWORK:-traefik}", "external": True}}
    hosted_env = {k: "" for k in LLM_KEYS}
    for t, spec in tenants.items():
        hosted_services[f"{t}-server"] = _server(topo, t, spec)
        volumes[f"{t}-data"] = {}
        hosted_env[_var(t, "ADMIN_PASSWORD")] = known[_var(t, "ADMIN_PASSWORD")]
        if spec["residency"] == "client":
            hosted_env[_var(t, "DATAPLANE_KEY")] = known[_var(t, "DATAPLANE_KEY")]
        else:
            hosted_services[f"{t}-clickhouse"] = _clickhouse(t) | {"networks": [t]}
            volumes[f"{t}-clickhouse"] = {}
            networks[t] = {}
            for k in ("CH_PASSWORD", "CH_RO_PASSWORD"):
                hosted_env[_var(t, k)] = known[_var(t, k)]
    hosted = out / "hosted"
    _write(
        hosted,
        {"name": "logpipe", "services": hosted_services, "volumes": volumes, "networks": networks},
        hosted_env,
    )
    written = [hosted]
    if any(s["residency"] == "hosted" for s in tenants.values()):
        shutil.copy(INIT_SCRIPT, hosted / "clickhouse-init.sh")

    for t, spec in tenants.items():
        if spec["residency"] != "client":
            continue
        host = f"{t}.{topo['domain']}"
        dataplane = {
            "image": f"{topo['images']}/logpipe-server:{topo['tag']}",
            "restart": "unless-stopped",
            "command": ["logpipe", "dataplane", "--store", "clickhouse"],
            "environment": {
                "LOGPIPE_DATAPLANE_URL": f"wss://{host}/dataplane",
                "LOGPIPE_DATAPLANE_KEY": f"${{{_var(t, 'DATAPLANE_KEY')}}}",
                **_clickhouse_env(t, "clickhouse"),
            },
            "depends_on": {"clickhouse": {"condition": "service_healthy"}},
        }
        client = out / f"client-{t}"
        _write(
            client,
            {
                "name": f"logpipe-{t}",
                "services": {"clickhouse": _clickhouse(t), "dataplane": dataplane},
                "volumes": {f"{t}-clickhouse": {}},
            },
            {
                _var(t, k): known[_var(t, k)]
                for k in ("DATAPLANE_KEY", "CH_PASSWORD", "CH_RO_PASSWORD")
            },
        )
        shutil.copy(INIT_SCRIPT, client / "clickhouse-init.sh")
        (client / "README.md").write_text(CLIENT_README.format(tenant=t, host=host), "utf-8")
        written.append(client)
    return written
